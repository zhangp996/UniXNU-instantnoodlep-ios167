#!/usr/bin/env python3
"""Device-owned verified-root kernel archive for the iOS 16.7.16 (20H392) arm64 build.

The reference scripts/build-verified-root-probe.py is a macOS test instrument pinned to
the iPadOS 17 reference images (hardcoded digests + xcrun), so it cannot authenticate this
board's 20H392 windows. Per the official iOS 16.x pattern (a device-owned verified-root
builder over the kit crypto), this recipe:

  1. compiles the real kit crypto (kits/VerifiedRoot/src/verified_root.c +
     adapters/xnu_crypto.c) from an actual XNU compile record, and
  2. embeds a HEADER-ONLY owner policy table (544-byte signed header per window + the
     395-byte owner anchor) generated by scripts/make-root-policies-linux.py.

The 4 KiB block hash tables are NOT linked into the kernel; they travel in the userdata
image as OS.vroot / SystemOS.vroot and NativeUfs reads them there (configureCachedTable).
Output: build/verified-root-xnu/libVerifiedRootProbe.a, the default XNU_VERIFIED_ROOT_ARCHIVE.
"""
import hashlib
import json
import os
from pathlib import Path
import struct
import subprocess
import sys
import uuid

ROOT = Path(os.environ.get('UNIXNU_TREE') or Path(__file__).resolve().parents[1])   # the assembled build tree
DEVICE = Path(os.environ['UNIXNU_DEVICE'])   # device repository (board package sources), set by the driver
KIT = ROOT / 'kits/VerifiedRoot'
OUT = ROOT / 'build/verified-root-xnu'
OUT.mkdir(parents=True, exist_ok=True)
WINDOWS = ['OS', 'SystemOS']
VR_HEADER_BYTES, VR_SIGNATURE_BYTES, VR_KEY_BYTES = 160, 384, 395
SIGNED = VR_HEADER_BYTES + VR_SIGNATURE_BYTES   # 544


def env_check(name, header, record):
    """Bind the linked policy to the board's independently measured root identity."""
    sha = os.environ.get('UNIXNU_ROOT_' + name.upper() + '_SHA256')
    var = 'XNU_OWNER_ROOT_VOLUME_UUID' if name == 'OS' else 'XNU_OWNER_CACHE_VOLUME_UUID'
    vol = os.environ.get(var)
    if sha and header[56:88].hex() != sha.lower():
        raise SystemExit(f'{name}: signed image digest differs from board [root] {sha}')
    if vol and bytes(uuid.UUID(vol).bytes) != header[40:56]:
        raise SystemExit(f'{name}: signed volume UUID differs from board [root] {vol}')
    if record['image_sha256'] != header[56:88].hex():
        raise SystemExit(f'{name}: verification record does not describe the signed header')


def load_policies():
    key, entries = None, []
    for name in WINDOWS:
        d = ROOT / f'build/verified-root-{name}'
        manifest = (d / 'manifest.bin').read_bytes()
        record = json.loads((d / 'verification.json').read_text())
        anchor = (d / 'trusted-key.bin').read_bytes()
        if (len(anchor) != VR_KEY_BYTES or record.get('real_c_signature_and_block_verification') is not True
                or record.get('original_image_modified') is not False
                or len(manifest) != SIGNED + 32 * record['blocks_verified']
                or manifest[56:88].hex() != record['image_sha256']):
            raise SystemExit(f'{name}: require the actually verified unchanged original full image')
        env_check(name, manifest[:SIGNED], record)
        if key is None:
            key = anchor
        if anchor != key:
            raise SystemExit('the root windows were not signed by one owner key')
        header_file = OUT / (name + '.header.bin')
        header_file.write_bytes(manifest[:SIGNED])
        entries.append((name, header_file, record))
    (OUT / 'verified_root_key.bin').write_bytes(key)
    return key, entries


def compile_record():
    recipe = ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/bsd/DEVELOPMENT/bsd_init.o.json'
    record = json.loads(recipe.read_text().strip().rstrip(','))
    # The replayed record carries -I paths into EXPORT_HDRS that the kernel build only
    # creates later (e.g. libsa, the kext SDK root). The kit crypto includes none of them,
    # so the directories only have to exist for -Wmissing-include-dirs (alioth record).
    args = record['arguments']
    for index, value in enumerate(args):
        if value == '-I' and index + 1 < len(args):
            path = Path(args[index + 1])
            if 'EXPORT_HDRS' in path.parts and not path.exists():
                path.mkdir(parents=True, exist_ok=True)
    return record


def replay(record, source, destination, extra):
    # Keep the ABI flags of the record but drop XNU's -W hardening set (the kit C is not
    # written against -Wunsafe-buffer-usage etc.), then re-add a controlled warning set,
    # exactly as scripts/build-arm-driver.py does for non-XNU driver sources.
    command, index, args = [], 0, record['arguments']
    while index < len(args):
        value = args[index]
        if value == record['file']:
            command.append(str(source))
        elif value == '-o':
            command += ['-o', str(destination)]
            index += 1
        elif value in ('-MF', '-MJ'):
            index += 1
        elif value in ('-MD', '-MP'):
            pass
        elif value == '-Xclang' and index + 1 < len(args) and args[index + 1].startswith('-W'):
            index += 1
        elif value.startswith('-W'):
            pass
        else:
            command.append(value)
        index += 1
    command += ['-Wall', '-Wextra', '-Werror', '-Wno-unused-parameter'] + extra
    result = subprocess.run(command, cwd=record['directory'], capture_output=True, text=True)
    (OUT / (Path(source).stem + '.log')).write_text(result.stdout + result.stderr)
    if result.returncode:
        raise SystemExit(result.stderr[-3500:])


def check_arm64(path):
    data = path.read_bytes()
    if struct.unpack_from('<4I', data) != (0xfeedfacf, 0x100000c, 0, 1):
        raise SystemExit(f'{path}: every verified-root object must remain ordinary ARM64')


def main():
    key, entries = load_policies()
    record = compile_record()
    includes = ['-I', str(KIT / 'include'), '-I', str(ROOT / 'build/corecrypto-2023/include')]
    objects = []
    sources = [KIT / 'src/verified_root.c', KIT / 'adapters/xnu_crypto.c',
               DEVICE / 'package/VerifiedRootProbe.c']
    for source in sources:
        destination = OUT / (source.stem + '.o')
        replay(record, source, destination, includes)
        check_arm64(destination)
        objects.append(destination)

    # Header-only policy table: one {manifest, manifestBytes=544} row per window.
    lines = ['// Generated owner policy table; header-only, hash tables live in userdata.',
             '.section __DATA_CONST,__const', '.balign 8',
             '.globl _verified_root_key', '_verified_root_key:',
             f'.incbin "{OUT / "verified_root_key.bin"}"']
    rows = []
    for name, header_file, _ in entries:
        label = '_' + name.lower() + '_policy_header'
        lines += ['.balign 8', label + ':', f'.incbin "{header_file}"']
        rows.append(f'.quad {label}, {SIGNED}')
    lines += ['.balign 8', '.globl _verified_root_policies', '_verified_root_policies:']
    lines += rows
    lines += ['.globl _verified_root_policy_count', '_verified_root_policy_count:',
              f'.quad {len(entries)}']
    assembly = OUT / 'inputs.S'
    assembly.write_text('\n'.join(lines) + '\n')
    inputs_obj = OUT / 'inputs.o'
    subprocess.run(['xcrun', 'clang', '-target', 'arm64-apple-ios17.0', '-c',
                    str(assembly), '-o', str(inputs_obj)], check=True)
    check_arm64(inputs_obj)
    objects.append(inputs_obj)

    archive = OUT / 'libVerifiedRootProbe.a'
    archive.unlink(missing_ok=True)
    subprocess.run(['xcrun', 'ar', 'rcs', str(archive), *map(str, objects)], check=True)
    report = dict(
        windows={name: dict(image_sha256=rec['image_sha256'], blocks_verified=rec['blocks_verified'],
                            volume_uuid=rec['volume_uuid'], manifest_header_bytes=SIGNED)
                 for name, _, rec in entries},
        trusted_key_sha256=hashlib.sha256(key).hexdigest(),
        policy_count=len(entries), header_only=True,
        hash_tables_in_userdata=[name + '.vroot' for name in WINDOWS],
        archive_sha256=hashlib.sha256(archive.read_bytes()).hexdigest(),
        boot_root_authenticated=False, hardware_tested=False)
    (OUT / 'build-report.json').write_text(json.dumps(report, indent=2) + '\n')
    print(f'verified-root: {len(entries)} header-only owner policies + real kit crypto -> {archive} '
          f'({report["archive_sha256"]})')


if __name__ == '__main__':
    main()
